"""SQLite order DDL, equivalent to db/schema.sql."""

SCHEMA = """
CREATE TABLE IF NOT EXISTS orders (
    order_id INTEGER PRIMARY KEY AUTOINCREMENT,
    buyer_id INTEGER NOT NULL REFERENCES users(telegram_user_id),
    seller_id INTEGER NOT NULL REFERENCES sellers(telegram_user_id),
    product_id INTEGER NOT NULL REFERENCES products(product_id),
    product_name TEXT NOT NULL,
    seller_name TEXT NOT NULL,
    unit_price_minor INTEGER NOT NULL CHECK (unit_price_minor >= 0),
    currency TEXT NOT NULL,
    quantity INTEGER NOT NULL CHECK (quantity > 0),
    buyer_name TEXT NOT NULL,
    buyer_phone TEXT NOT NULL,
    buyer_phone_verified INTEGER NOT NULL CHECK (buyer_phone_verified IN (0, 1)),
    consent_version TEXT NOT NULL,
    confirmation_key TEXT NOT NULL UNIQUE,
    status TEXT NOT NULL CHECK (status IN ('PENDING', 'ACCEPTED', 'DECLINED', 'CANCELLED', 'EXPIRED', 'COMPLETED')),
    version INTEGER DEFAULT 1 NOT NULL,
    created_at TEXT NOT NULL,
    updated_at TEXT NOT NULL,
    confirmed_at TEXT NOT NULL,
    expires_at TEXT NOT NULL,
    decided_at TEXT,
    completed_at TEXT,
    cancelled_by INTEGER,
    cancellation_reason TEXT,
    buyer_erased_at TEXT,
    seller_erased_at TEXT,
    CHECK (buyer_id <> seller_id)
);
CREATE INDEX IF NOT EXISTS orders_buyer_idx ON orders(buyer_id, order_id);
CREATE INDEX IF NOT EXISTS orders_seller_idx ON orders(seller_id, order_id);
CREATE INDEX IF NOT EXISTS orders_expiry_idx ON orders(status, expires_at);

CREATE TABLE IF NOT EXISTS order_notifications (
    event_id INTEGER PRIMARY KEY AUTOINCREMENT,
    order_id INTEGER NOT NULL REFERENCES orders(order_id),
    order_version INTEGER NOT NULL,
    recipient_id INTEGER NOT NULL REFERENCES users(telegram_user_id),
    event_kind TEXT NOT NULL,
    state TEXT DEFAULT 'PENDING' NOT NULL CHECK (state IN ('PENDING', 'SENDING', 'SENT', 'FAILED', 'SUPPRESSED')),
    attempt_count INTEGER DEFAULT 0 NOT NULL,
    created_at TEXT NOT NULL,
    next_attempt_at TEXT NOT NULL,
    lease_token TEXT,
    lease_until TEXT,
    last_error TEXT,
    message_id INTEGER,
    delivered_at TEXT,
    UNIQUE (order_id, order_version, recipient_id)
);
CREATE INDEX IF NOT EXISTS order_notify_due_idx ON order_notifications(state, next_attempt_at);
"""

