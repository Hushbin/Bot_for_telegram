-- Owned by SME_SCHEMA. The bot connects as SME_BOT and has DML only.
-- deleted_at marks erased rows: personal columns are overwritten with '[deleted]'
-- rather than the row being removed, so the runtime user needs no DELETE grant.
-- Keep scripts/setup_db.py COLUMN_MIGRATIONS and COLUMN_RENAMES in step with any column
-- added or renamed here. Prices are minor units (cents) in the row's currency; category
-- columns hold the key from catalog.py (for example 'clothing'), never the label.
CREATE TABLE users (
    telegram_user_id NUMBER(19) PRIMARY KEY,
    full_name VARCHAR2(160 CHAR) NOT NULL,
    email VARCHAR2(254 CHAR) NOT NULL,
    phone VARCHAR2(40 CHAR) NOT NULL,
    phone_verified NUMBER(1) DEFAULT 0 NOT NULL
        CHECK (phone_verified IN (0, 1)),
    role VARCHAR2(8 CHAR) DEFAULT 'CUSTOMER' NOT NULL
        CHECK (role IN ('CUSTOMER', 'SELLER')),
    preferred_category VARCHAR2(80 CHAR),
    deleted_at TIMESTAMP WITH TIME ZONE,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE TABLE sellers (
    telegram_user_id NUMBER(19) PRIMARY KEY
        REFERENCES users (telegram_user_id),
    business_name VARCHAR2(160 CHAR) NOT NULL,
    business_email VARCHAR2(254 CHAR) NOT NULL,
    address VARCHAR2(400 CHAR) NOT NULL,
    business_phone VARCHAR2(40 CHAR) NOT NULL,
    deleted_at TIMESTAMP WITH TIME ZONE,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE TABLE products (
    product_id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    seller_telegram_user_id NUMBER(19) NOT NULL
        REFERENCES sellers (telegram_user_id),
    name VARCHAR2(160 CHAR) NOT NULL,
    category VARCHAR2(80 CHAR) NOT NULL,
    description VARCHAR2(1000 CHAR),
    price_minor NUMBER(12) NOT NULL CHECK (price_minor >= 0),
    currency VARCHAR2(3 CHAR) DEFAULT 'USD' NOT NULL,
    stock_quantity NUMBER(10) NOT NULL CHECK (stock_quantity >= 0),
    photo_object_key VARCHAR2(512 CHAR),
    photo_version_id VARCHAR2(128 CHAR),
    telegram_photo_file_id VARCHAR2(1024 CHAR),
    telegram_photo_bot_id NUMBER(19),
    deleted_at TIMESTAMP WITH TIME ZONE,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE INDEX products_category_idx ON products (category, product_id);
CREATE INDEX products_seller_idx ON products (seller_telegram_user_id, product_id);

CREATE TABLE orders (
    order_id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    buyer_id NUMBER(19) NOT NULL REFERENCES users(telegram_user_id),
    seller_id NUMBER(19) NOT NULL REFERENCES sellers(telegram_user_id),
    product_id NUMBER NOT NULL REFERENCES products(product_id),
    product_name VARCHAR2(160 CHAR) NOT NULL,
    seller_name VARCHAR2(160 CHAR) NOT NULL,
    unit_price_minor NUMBER(12) NOT NULL CHECK (unit_price_minor >= 0),
    currency VARCHAR2(3 CHAR) NOT NULL,
    quantity NUMBER(10) NOT NULL CHECK (quantity > 0),
    buyer_name VARCHAR2(160 CHAR) NOT NULL,
    buyer_phone VARCHAR2(40 CHAR) NOT NULL,
    buyer_phone_verified NUMBER(1) NOT NULL CHECK (buyer_phone_verified IN (0, 1)),
    consent_version VARCHAR2(32 CHAR) NOT NULL,
    confirmation_key VARCHAR2(32 CHAR) NOT NULL UNIQUE,
    status VARCHAR2(12 CHAR) NOT NULL CHECK (status IN ('PENDING', 'ACCEPTED', 'DECLINED', 'CANCELLED', 'EXPIRED', 'COMPLETED')),
    version NUMBER(10) DEFAULT 1 NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    confirmed_at TIMESTAMP WITH TIME ZONE NOT NULL,
    expires_at TIMESTAMP WITH TIME ZONE NOT NULL,
    decided_at TIMESTAMP WITH TIME ZONE,
    completed_at TIMESTAMP WITH TIME ZONE,
    cancelled_by NUMBER(19),
    cancellation_reason VARCHAR2(32 CHAR),
    buyer_erased_at TIMESTAMP WITH TIME ZONE,
    seller_erased_at TIMESTAMP WITH TIME ZONE,
    CHECK (buyer_id <> seller_id)
);
CREATE INDEX orders_buyer_idx ON orders(buyer_id, order_id);
CREATE INDEX orders_seller_idx ON orders(seller_id, order_id);
CREATE INDEX orders_expiry_idx ON orders(status, expires_at);

CREATE TABLE order_notifications (
    event_id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    order_id NUMBER NOT NULL REFERENCES orders(order_id),
    order_version NUMBER(10) NOT NULL,
    recipient_id NUMBER(19) NOT NULL REFERENCES users(telegram_user_id),
    event_kind VARCHAR2(16 CHAR) NOT NULL,
    state VARCHAR2(12 CHAR) DEFAULT 'PENDING' NOT NULL CHECK (state IN ('PENDING', 'SENDING', 'SENT', 'FAILED', 'SUPPRESSED')),
    attempt_count NUMBER(10) DEFAULT 0 NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    next_attempt_at TIMESTAMP WITH TIME ZONE NOT NULL,
    lease_token VARCHAR2(32 CHAR),
    lease_until TIMESTAMP WITH TIME ZONE,
    last_error VARCHAR2(40 CHAR),
    message_id NUMBER(19),
    delivered_at TIMESTAMP WITH TIME ZONE,
    UNIQUE (order_id, order_version, recipient_id)
);
CREATE INDEX order_notify_due_idx ON order_notifications(state, next_attempt_at);


-- One reusable row per Telegram account; survives account erasure until UTC rollover.
CREATE TABLE abuse_limits (
    telegram_user_id NUMBER(19) PRIMARY KEY REFERENCES users(telegram_user_id),
    window_start TIMESTAMP WITH TIME ZONE NOT NULL,
    listing_count NUMBER(10) DEFAULT 0 NOT NULL CHECK (listing_count >= 0),
    order_count NUMBER(10) DEFAULT 0 NOT NULL CHECK (order_count >= 0),
    photo_attempt_count NUMBER(10) DEFAULT 0 NOT NULL CHECK (photo_attempt_count >= 0),
    last_listing_at TIMESTAMP WITH TIME ZONE,
    last_order_at TIMESTAMP WITH TIME ZONE,
    last_photo_at TIMESTAMP WITH TIME ZONE,
    blocked_until TIMESTAMP WITH TIME ZONE
);
